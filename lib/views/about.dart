@immutable

class AboutView extends ConsumerWidget {
  const AboutView({super.key});


  Future<void> _checkUpdate(BuildContext context, WidgetRef ref) async {
    if (ref.read(loadingProvider(LoadingTag.checkUpdate))) return;
    // 琉璃：走面板清单 + 多源测速（上游 GitHub 在境内常不通）
    await showLiuliUpdate(context, current: globalState.packageInfo.version);
  }

  Widget _buildLinkItem({
    required Glyph glyph,
    required String title,
    required String url,
    required String label,
  }) {
    return ListItem(
      leading: _LinkBadge(glyph: glyph),
      title: Text(title),
      subtitle: Text(label, maxLines: 1, overflow: TextOverflow.ellipsis),
      trailing: const GlyphIcon(AppGlyphs.openExternal),
      onTap: () {
        dialogs.openUrl(url);
      },
    );
  }

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final appLocalizations = context.appLocalizations;
    final isLoading = ref.watch(loadingProvider(LoadingTag.checkUpdate));
    return Scaffold(
      isLoading: isLoading,
      title: appLocalizations.about,
      body: ListView(
        padding: const EdgeInsets.symmetric(horizontal: 16).copyWith(
          top: context.contentTopPadding,
          bottom: 32 + context.bottomInset,
        ),
        children: [
          _AboutHero(
            isCheckingUpdate: isLoading,
            onCheckUpdate: () {
              _checkUpdate(context, ref);
            },
            onEnterDeveloperMode: () {
              ref
                  .read(appSettingProvider.notifier)
                  .update((state) => state.copyWith(developerMode: true));
              dialogs.showBanner(
                appLocalizations.developerModeEnableTip,
                level: BannerLevel.success,
              );
            },
          ),
          const SizedBox(height: 8),
          generateSection(
            title: appLocalizations.more,
            items: [
              _buildLinkItem(
                glyph: AppGlyphs.code,
                title: appLocalizations.project,
                url: 'https://github.com/lxyit24/liuli-desktop',
                label: 'github.com/lxyit24/liuli-desktop',
              ),
              _buildLinkItem(
                glyph: AppGlyphs.cpu,
                title: appLocalizations.core,
                url: 'https://github.com/chen08209/Clash.Meta/tree/FlClash',
                label: 'github.com/chen08209/Clash.Meta',
              ),
              _buildLinkItem(
                glyph: AppGlyphs.gavel,
                title: '开源许可',
                url: 'https://www.gnu.org/licenses/gpl-3.0.html',
                label: 'GNU GPL-3.0',
              ),
              _buildLinkItem(
                glyph: AppGlyphs.profiles,
                title: '用户协议',
                url: '$liuliBaseCached/terms',
                label: 'liuli · 用户协议',
              ),
              _buildLinkItem(
                glyph: AppGlyphs.lock,
                title: '隐私政策',
                url: '$liuliBaseCached/privacy',
                label: 'liuli · 隐私政策',
              ),
            ],
          ),
          generateSection(
            title: '上游与致谢',
            items: [
              _buildLinkItem(
                glyph: AppGlyphs.sparkle,
                title: 'FlClash（本项目上游）',
                url: 'https://github.com/chen08209/FlClash',
                label: 'github.com/chen08209/FlClash',
              ),
              _buildLinkItem(
                glyph: AppGlyphs.account,
                title: '上游作者',
                url: 'https://github.com/chen08209',
                label: 'chen08209 及 FlClash 贡献者',
              ),
            ],
          ),
        ],
      ),
    );
  }
}

